def infer_pending(engine, request_factory, request, inputs, payload, seen, batch_limit):
    """Yield only unsaved requests, preserving Swift's documented batch order."""
    assert batch_limit > 0
    pending = [r for r in inputs if r['id'] not in seen]
    for start in range(0, len(pending), batch_limit):
        batch = pending[start:start+batch_limit]
        results = engine.infer([request_factory(**copy.deepcopy(payload[r['id']])) for r in batch], request, use_tqdm=False)
        if len(results) != len(batch):
            raise RuntimeError(f'inference returned {len(results)} results for {len(batch)} requests')
        for row, result in zip(batch, results):
            if isinstance(result, Exception):
                raise result
            yield row, result


def evaluation_template(args, processor):
    """PT trains raw material; evaluation always reconstructs the chat template."""
    args.use_chat_template = True
    template = args.get_template(processor)
    assert template.use_chat_template and template.template_meta.support_system
    return template


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--root',type=Path,required=True);ap.add_argument('--work',type=Path,required=True);ap.add_argument('--model',choices=MODELS,required=True);ap.add_argument('--objective',choices=['sft','pt'],required=True);ap.add_argument('--modality',choices=['text','vision'],required=True);ap.add_argument('--gpu',required=True);ap.add_argument('--protocols',nargs='+',choices=['strict','cot'],default=['strict']);ap.add_argument('--preflight-only',action='store_true');ap.add_argument('--preflight-smoke-adapter',action='store_true');a=ap.parse_args()
    data=a.root.resolve();work=a.work.resolve();name=f'{a.model}_{a.objective}_{a.modality}';job=work/'jobs'/name
    if a.preflight_smoke_adapter:
        assert a.preflight_only,'Smoke adapters must never be used for full evaluation'
        cp=Path(read(work/'smoke'/name/'validated.json')['checkpoint'])
    else:
        cp=Path(read(job/'checkpoint_manifest.json')['path'])
        assert final_checkpoint(job/'checkpoint',5)==cp
    out=work/('eval_preflight' if a.preflight_only else 'evaluations')/name;out.mkdir(parents=True,exist_ok=True)
    os.environ.update(environment(a.gpu,data))
    # Every adapter is evaluated on all four input/output directions. The
    # adapter modality identifies how it was trained; it does not restrict
    # the evaluation set.
    directions=['T2T','T2V','V2T','V2V']
    labels=ev.id_map(rows(data/'audit/eval_labels.jsonl'),data);audit=ev.id_map(rows(data/'audit/sample_audit.jsonl'),data)
    config={'model':str(MODELS[a.model]),'adapter':ev.checkpoint(cp),'directions':directions,'protocols':{'strict':{'max_tokens':32,'enable_thinking':False},'cot':{'max_tokens':1536,'enable_thinking':True}},'temperature':0,'seed':42,'max_pixels':1003520,'parser':COT_PARSER,'source_hashes':{d:sha(data/d/'eval.jsonl') for d in directions},'labels_sha256':sha(data/'audit/eval_labels.jsonl'),'audit_sha256':sha(data/'audit/sample_audit.jsonl'),'evaluator_sha256':sha(Path(ev.__file__)),'adapter_evaluator_sha256':sha(Path(__file__))}
    # Qwen Instruct checkpoints are non-thinking variants. Elicit reasoning
    # with the same CoT prompt rather than inserting a native <think> prefix.
    config['protocols']['cot']['enable_thinking']=a.model=='glm46'
    config['protocols']['cot']['reasoning_mode']='native' if a.model=='glm46' else 'prompted'
    config['samples_per_direction']=1 if a.preflight_only else 2000
    config['inference_batch_size']={'strict':1,'cot':1} if a.preflight_only else {'strict':16,'cot':8}
    if a.objective=='pt':config['template_reload']='reconstruct-chat-template-v1'
    manifest=out/'manifest.json'
    if manifest.exists():
        old_config=read(manifest)['config']
        if old_config != config:
            # Existing rows were generated by the previous evaluator revision.
            # Preserve that immutable manifest while allowing a safe strict-only
            # resume after the protocol scheduler changed.
            old_cmp=dict(old_config); new_cmp=dict(config)
            old_cmp.pop('adapter_evaluator_sha256',None); new_cmp.pop('adapter_evaluator_sha256',None)
            if a.objective=='pt' and 'template_reload' not in old_cmp:
                assert not any(p.stat().st_size for p in out.glob('*/*/raw.jsonl')),'Cannot change PT template after generating responses'
                new_cmp.pop('template_reload')
                assert old_cmp==new_cmp and old_config.get('adapter_evaluator_sha256') in PROTOCOL_SCHEDULING_PREDECESSORS,'Unreviewed PT evaluation revision'
                manifest.rename(out/'manifest.before_pt_template_fix.json')
                save(manifest,{'signature':ev.digest(config),'config':config,'created_at':ev.now(),'revision_reason':'PT evaluated with reconstructed chat template; predecessor generated zero responses'})
                old_config=config
                old_cmp=dict(config);new_cmp=dict(config)
                old_cmp.pop('adapter_evaluator_sha256',None);new_cmp.pop('adapter_evaluator_sha256',None)
            assert old_cmp==new_cmp,'Cannot resume changed evaluation'
            assert old_config.get('adapter_evaluator_sha256') in PROTOCOL_SCHEDULING_PREDECESSORS or old_config==config,'Unreviewed evaluator revision; cannot resume'
            save(out/'evaluator_revision.json',{'original_sha256':old_config['adapter_evaluator_sha256'],'current_sha256':config['adapter_evaluator_sha256'],'reason':'Reviewed scheduler/provenance changes; chat-template repair applies only to PT tasks with no generated responses','protocols':a.protocols,'updated_at':ev.now()})
            config=old_config
    else:save(manifest,{'signature':ev.digest(config),'config':config,'created_at':ev.now()})
    with ev.run_lock(out/'.lock'):
        from swift.infer_engine import TransformersEngine, InferRequest, RequestConfig
        from swift.utils import seed_everything
        import torch
        seed_everything(42)
        kwargs={'template_type':'glm4_5v'} if a.model=='glm46' else {}
        print('loading',name,'on GPU',a.gpu,flush=True)
        class PTEvaluationEngine(TransformersEngine):
            def _get_template(self, processor, template_type=None):
                from swift.arguments import BaseArguments
                return evaluation_template(BaseArguments.from_pretrained(str(cp)),processor)
        engine_class=PTEvaluationEngine if a.objective=='pt' else TransformersEngine
        engine=engine_class(str(MODELS[a.model]),adapters=[str(cp)],torch_dtype=torch.bfloat16,device_map='cuda:0',max_batch_size=max(config['inference_batch_size'].values()),attn_impl='sdpa',**kwargs)
        engine.template.use_chat_template=True
        for protocol in a.protocols:
            engine.template.enable_thinking=protocol=='cot' and a.model=='glm46'
            fmt='cot' if protocol=='cot' else ('glm-box' if a.model=='glm46' else 'strict')
            request=RequestConfig(max_tokens=1536 if protocol=='cot' else 32,temperature=0,seed=42,return_details=True)
            for direction in directions:
                folder=out/protocol/direction;folder.mkdir(parents=True,exist_ok=True)
                inputs=[ev.prepare_row(r,data,direction,fmt) for r in rows(data/direction/'eval.jsonl')]
                assert len(inputs)==len(labels)==2000 and {r['id'] for r in inputs}==set(labels)
                if a.preflight_only:inputs=inputs[:1]
                payload={r['id']:{k:r[k] for k in ('messages','images') if k in r} for r in inputs}
                ev.save_rows(folder/'eval.input.jsonl',inputs)
                raw=folder/'raw.jsonl';saved=ev.read_rows(raw,allow_partial_tail=True)[0] if raw.exists() else []
                seen={}
                for r in saved:
                    assert r['id'] not in seen and r['prompt_sha256']==ev.digest(payload[r['id']]),'saved row mismatch'
                    assert r['adapter_sha256']==config['adapter']['sha256'],'saved adapter mismatch'
                    seen[r['id']]=r
                if raw.exists() and raw.read_bytes() and not raw.read_bytes().endswith(b'\n'):ev.save_rows(raw,saved)
                print(name,protocol,direction,'saved',len(seen),'remaining',len(inputs)-len(seen),flush=True)
                with raw.open('a',encoding='utf8') as f:
                    batch_limit=config['inference_batch_size'][protocol]
                    for r,res in infer_pending(engine,InferRequest,request,inputs,payload,seen,batch_limit):
                        c=res.choices[0];msg=c.message
                        record={'id':r['id'],'qid':r['qid'],'response':msg.content or '',
                            'reasoning_content':getattr(msg,'reasoning_content',None),'finish_reason':c.finish_reason,'usage':dataclasses.asdict(res.usage),
                            'prompt_sha256':ev.digest(payload[r['id']]),'adapter_sha256':config['adapter']['sha256'],'protocol':protocol,'direction':direction,'max_tokens':request.max_tokens,'saved_at':ev.now()}
                        f.write(json.dumps(record,ensure_ascii=False)+'\n');f.flush();os.fsync(f.fileno());seen[r['id']]=record
                        save(folder/'progress.json',{'saved':len(seen),'expected':len(inputs),'batch_size':batch_limit,'updated_at':ev.now()})
                        if len(seen)%100==0 or len(seen)==len(inputs):print(name,protocol,direction,len(seen),f'/{len(inputs)}',flush=True)
                report,scored=ev.score(inputs,seen,labels,audit,direction,fmt)
                report.update(adapter=str(cp),protocol=protocol,updated_at=ev.now(),truncated=sum(x.get('finish_reason')=='length' for x in seen.values()),input_hash=ev.digest(inputs))
                for x in scored:
                    x.update(finish_reason=seen[x['id']]['finish_reason'],usage=seen[x['id']]['usage'],reasoning_content=seen[x['id']].get('reasoning_content'))
                ev.save_rows(folder/'predictions.jsonl',[seen[r['id']] for r in inputs]);ev.save_rows(folder/'results.jsonl',scored);ev.save_rows(folder/'errors.jsonl',[x for x in scored if not x['correct']]);save(folder/'report.json',report)
                print(name,protocol,direction,'accuracy',report['accuracy'],'valid',report['valid'],flush=True)
        save(out/'status.json',{'status':'complete','protocols':a.protocols,'cells':4*len(a.protocols),'responses':4*len(a.protocols)*(1 if a.preflight_only else 2000),'finished_at':ev.now()})
if __name__=='__main__':main()
